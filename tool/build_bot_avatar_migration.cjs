const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve('output/bot-avatars/v1');
const manifest = JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const generated = JSON.parse(fs.readFileSync(path.join(root,'generated.json'),'utf8'));
const ref = fs.readFileSync('supabase/.temp/project-ref','utf8').trim();
if (!/^[a-z]{20}$/.test(ref)) throw Error('Unexpected project reference');
if(manifest.length!==164 || generated.length!==164) throw Error('All 164 unique avatars must be generated first');
const hashes = new Set();
const rows = manifest.map(account => {
  if(!generated.some(g=>g.id===account.id)) throw Error(`Missing image ${account.id}`);
  if (/papatya|gülkurusu|kırçiçeği|akşamsefası/.test(account.username.toLocaleLowerCase('tr')) && account.gender!=='female') throw Error('Flower name must have female avatar');
  if(account.gender==='female' && !['photo','illustration'].includes(account.category)) throw Error('Female name must have female person');
  if(account.gender==='male' && !['photo','illustration'].includes(account.category)) throw Error('Male name must have male person');
  const bytes = fs.readFileSync(path.join(root,'images',account.file));
  if(bytes.length>30720 || bytes[0]!==0xff || bytes[1]!==0xd8) throw Error('Expected compact JPEG');
  const hash=crypto.createHash('sha256').update(bytes).digest('hex');
  if(hashes.has(hash)) throw Error('Duplicate avatar content');
  hashes.add(hash);
  return {...account, sha256:hash, bytes:bytes.length, url:`https://${ref}.supabase.co/storage/v1/object/public/avatars/${account.storage_path}`};
});
const payload = rows.map(({id,username,previous_avatar,gender,category,storage_path,sha256,bytes,url})=>({id,username,previous_avatar,gender,category,storage_path,sha256,bytes,url}));
fs.writeFileSync(path.join(root,'assignments.json'), JSON.stringify(payload,null,2)+'\n');
const sql = `-- 164 individual AI-generated avatars, optimized to 256x256 JPEG (<=30KB).
-- Assets must be uploaded to the existing public avatars bucket first.
-- Explicit bot UUID/name mapping; Auth accounts and gameplay fields are untouched.
-- Generated by tool/build_bot_avatar_migration.cjs from the reviewed manifest.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';
CREATE TEMP TABLE bot_avatar_plan ON COMMIT DROP AS
SELECT * FROM jsonb_to_recordset($avatars$${JSON.stringify(payload)}$avatars$::jsonb)
 AS p(id uuid,username text,previous_avatar text,gender text,category text,
   storage_path text,sha256 text,bytes integer,url text);

DO $preflight$
BEGIN
  IF current_user<>'postgres' THEN RAISE EXCEPTION 'BOT_AVATARS_POSTGRES_REQUIRED'; END IF;
  LOCK TABLE public.users,public.profiles IN SHARE ROW EXCLUSIVE MODE;
  IF (SELECT count(*) FROM bot_avatar_plan)<>164
    OR (SELECT count(DISTINCT id) FROM bot_avatar_plan)<>164
    OR (SELECT count(DISTINCT url) FROM bot_avatar_plan)<>164
    OR (SELECT count(DISTINCT sha256) FROM bot_avatar_plan)<>164 THEN
    RAISE EXCEPTION 'BOT_AVATARS_UNIQUE_PLAN_REQUIRED';
  END IF;
  IF EXISTS(SELECT 1 FROM bot_avatar_plan p LEFT JOIN public.users u ON u.id=p.id
    LEFT JOIN public.profiles profile ON profile.id=p.id
    WHERE u.id IS NULL OR profile.id IS NULL OR u.is_bot IS DISTINCT FROM true
      OR u.username IS DISTINCT FROM p.username
      OR EXISTS(SELECT 1 FROM auth.users a WHERE a.id=p.id)
      OR (u.avatar_url IS DISTINCT FROM p.previous_avatar AND u.avatar_url IS DISTINCT FROM p.url)) THEN
    RAISE EXCEPTION 'BOT_AVATARS_IDENTITY_CHANGED';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM storage.buckets WHERE id='avatars' AND public) THEN
    RAISE EXCEPTION 'BOT_AVATARS_PUBLIC_BUCKET_REQUIRED';
  END IF;
  IF EXISTS(SELECT 1 FROM bot_avatar_plan p LEFT JOIN storage.objects o
    ON o.bucket_id='avatars' AND o.name=p.storage_path
    WHERE o.id IS NULL OR (o.metadata->>'size')::bigint IS DISTINCT FROM p.bytes::bigint
      OR o.metadata->>'mimetype' IS DISTINCT FROM 'image/jpeg'
      OR p.bytes>30720) THEN
    RAISE EXCEPTION 'BOT_AVATARS_UPLOAD_REQUIRED';
  END IF;
END $preflight$;

CREATE SCHEMA IF NOT EXISTS okeyix_bot_avatar_private;
REVOKE ALL ON SCHEMA okeyix_bot_avatar_private FROM PUBLIC,anon,authenticated,service_role;
CREATE TABLE IF NOT EXISTS okeyix_bot_avatar_private.assignments(
  version text NOT NULL,user_id uuid NOT NULL,username text NOT NULL,
  previous_users_avatar text,previous_profiles_avatar text,
  avatar_url text NOT NULL,storage_path text NOT NULL,sha256 text NOT NULL,
  bytes integer NOT NULL CHECK(bytes BETWEEN 1 AND 30720),
  gender text NOT NULL CHECK(gender IN ('female','male','neutral')),
  category text NOT NULL,assigned_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(version,user_id),UNIQUE(version,avatar_url),UNIQUE(version,sha256)
);
ALTER TABLE okeyix_bot_avatar_private.assignments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON okeyix_bot_avatar_private.assignments FROM PUBLIC,anon,authenticated,service_role;
INSERT INTO okeyix_bot_avatar_private.assignments
  (version,user_id,username,previous_users_avatar,previous_profiles_avatar,
   avatar_url,storage_path,sha256,bytes,gender,category)
SELECT 'v1',p.id,p.username,u.avatar_url,profile.avatar,p.url,p.storage_path,p.sha256,
  p.bytes,p.gender,p.category
FROM bot_avatar_plan p JOIN public.users u ON u.id=p.id
JOIN public.profiles profile ON profile.id=p.id
ON CONFLICT(version,user_id) DO NOTHING;
CREATE TEMP TABLE bot_avatar_before ON COMMIT DROP AS
SELECT u.id,to_jsonb(u)-'avatar_url' AS user_fields,to_jsonb(profile)-'avatar' AS profile_fields
FROM bot_avatar_plan p JOIN public.users u ON u.id=p.id JOIN public.profiles profile ON profile.id=p.id;
UPDATE public.users u SET avatar_url=p.url FROM bot_avatar_plan p WHERE p.id=u.id;
UPDATE public.profiles profile SET avatar=p.url FROM bot_avatar_plan p WHERE p.id=profile.id;
DO $verify$
BEGIN
  IF EXISTS(SELECT 1 FROM bot_avatar_plan p JOIN public.users u ON u.id=p.id
    JOIN public.profiles profile ON profile.id=p.id JOIN bot_avatar_before b ON b.id=p.id
    WHERE u.avatar_url IS DISTINCT FROM p.url OR profile.avatar IS DISTINCT FROM p.url
      OR to_jsonb(u)-'avatar_url' IS DISTINCT FROM b.user_fields
      OR to_jsonb(profile)-'avatar' IS DISTINCT FROM b.profile_fields) THEN
    RAISE EXCEPTION 'BOT_AVATARS_POSTCHECK_FAILED';
  END IF;
  RAISE NOTICE 'Assigned 164 distinct 256px avatars: % bytes total; all gameplay and moderation fields preserved.',
    (SELECT sum(bytes) FROM bot_avatar_plan);
END $verify$;
COMMIT;
`;
const migration = 'supabase/migrations/20261126000200_natural_bot_avatars.sql';
fs.writeFileSync(migration,sql);
console.log(JSON.stringify({migration,count:rows.length,totalBytes:rows.reduce((s,x)=>s+x.bytes,0),uniqueHashes:hashes.size}));
